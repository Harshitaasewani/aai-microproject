"""Report generation: Markdown compliance report + JSON + Audit Evidence Package (advanced feature 5)."""
from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path

import pandas as pd

from .data_loader import MarketData


def to_markdown(r: dict) -> str:
    p = r["product"]
    L = [f"# Trust & Compliance Report — {p['title']}",
         "",
         f"**Case:** {r['case_id']} · **Region:** {r['region']} · **As of:** {r['as_of_utc'][:16]} UTC  ",
         f"**Seller:** {p['seller_name']} ({p['seller_id']}, account {p['seller_account_age_days']} days old)  ",
         f"**Reviews:** {p['reviews']} · **Avg rating:** {p['avg_rating']}★ · **Verified-purchase rate:** "
         f"{p['verified_purchase_rate']} · **Median reviewer account age at review:** {p['reviewer_account_age_median_days']} days",
         "",
         f"## Risk score: {r['risk_score']:.0f}/100 — {r['tier']}",
         f"**Decision status:** `{r['decision']['status']}` · **Routed to:** {r['decision']['queue']}  ",
         f"**Enforcement:** {r['decision']['enforcement']}",
         ""]
    if r["decision"]["conflict"]:
        L += [f"> ⚠ **Conflicting signals:** {r['decision']['conflict']}. Case flagged for manual review instead of auto-deciding.", ""]
    L += ["## Summary", "", "| Field | Value |", "|---|---|"]
    for k, v in r["summary_table"].items():
        L.append(f"| {k} | {str(v).replace('|', '/')} |")
    L += ["", "## Agent scores", "", "| Agent | Risk signal (0-1) | Confidence | Summary |", "|---|---|---|---|"]
    for k, a in r["agents"].items():
        L.append(f"| {a['agent']} | {a['score']:.2f} | {a['confidence']:.2f} | {a['summary']} |")
    L += ["", "## Findings (audit trail)", "",
          "| ID | Severity | Finding | Policy clause | Regulatory reference | Evidence |", "|---|---|---|---|---|---|"]
    for f in r["findings"]:
        L.append(f"| {f['finding_id']} | {f['severity']} | **{f['title']}** — {f['detail']} | {f['policy_clause']} | "
                 f"{f['regulatory_reference'] or '—'} | {f['evidence_count']} item(s), sha256 `{f['evidence_sha256'][:12]}…` |")
    L += ["", "## Recommended actions (for human approval)", ""] + [f"- {x}" for x in r["decision"]["recommendations"]]
    cm = r["case_memory"]
    L += ["", "## Historical precedent", "", f"{cm['headline']}.",
          "", "Outcome mix: " + ", ".join(f"{k} {v:.0%}" for k, v in cm["outcome_distribution"].items())]
    if r["data_quality"]:
        L += ["", "## Data quality notes", ""] + [f"- {x}" for x in r["data_quality"]]
    L += ["", "---", "*Generated by TrustGuard (PS-13 prototype). This report is a detection and evidence layer; "
          "it is not an enforcement decision.*"]
    return "\n".join(L)


def save(r: dict, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    pid = r["product"]["product_id"]
    j = out_dir / f"{pid}_report.json"
    m = out_dir / f"{pid}_report.md"
    j.write_text(json.dumps(r, indent=2, default=str))
    m.write_text(to_markdown(r))
    return j, m


def evidence_package(r: dict, market: MarketData) -> bytes:
    """Single exportable packet for legal/compliance hand-off, with a SHA-256 manifest."""
    pid = r["product"]["product_id"]
    files: dict[str, bytes] = {}
    files["report.json"] = json.dumps(r, indent=2, default=str).encode()
    files["report.md"] = to_markdown(r).encode()

    audit = pd.DataFrame([{k: v for k, v in f.items() if k != "evidence"} for f in r["findings"]])
    files["audit_trail.csv"] = audit.to_csv(index=False).encode()

    rv = market.reviews[market.reviews.product_id == pid].merge(market.reviewers, on="reviewer_id", how="left")
    flagged = set(r["agents"]["linguistic"]["metrics"].get("flagged_review_ids", []))
    ring = r["agents"]["network"]["metrics"].get("ring_assignment", {})
    burst = set(_all_evidence_ids(r, "volume_spike"))
    rv["linguistic_flag"] = rv.review_id.isin(flagged)
    rv["in_burst_window"] = rv.review_id.isin(burst)
    rv["ring_cluster"] = rv.reviewer_id.map(ring)
    sus = rv[rv.linguistic_flag | rv.in_burst_window | rv.ring_cluster.notna()]
    files["flagged_reviews.csv"] = sus[["review_id", "reviewer_id", "rating", "timestamp", "verified_purchase", "text",
                                        "ip_prefix", "device_id", "account_created", "linguistic_flag",
                                        "in_burst_window", "ring_cluster"]].to_csv(index=False).encode()

    ev = market.seller_events[market.seller_events.seller_id == r["product"]["seller_id"]]
    files["seller_history.csv"] = ev.to_csv(index=False).encode()

    imgs = {market.products.set_index("product_id").loc[pid, "image_file"]}
    for f in r["findings"]:
        if f["flag_type"] in ("reused_image", "brand_image_match"):
            for e in f["evidence"]:
                imgs.add(e.get("image") or e.get("reference"))
    for name in filter(None, imgs):
        path = market.image_dir / name
        if path.exists():
            files[f"images/{name}"] = path.read_bytes()

    manifest = {name: hashlib.sha256(b).hexdigest() for name, b in files.items()}
    files["MANIFEST.json"] = json.dumps({"case_id": r["case_id"], "files_sha256": manifest}, indent=2).encode()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, b in files.items():
            z.writestr(f"{r['case_id']}/{name}", b)
    return buf.getvalue()


def _all_evidence_ids(r: dict, flag_type: str) -> list[str]:
    for a in r["agents"].values():
        for f in a["flags"]:
            if f["flag_type"] == flag_type:
                return [e for e in f["evidence"] if isinstance(e, str)]
    return []
